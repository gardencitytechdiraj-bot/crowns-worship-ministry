const header = document.querySelector('[data-header]');
const menuToggle = document.querySelector('[data-menu-toggle]');
const mobileNav = document.querySelector('[data-mobile-nav]');
const languageButtons = document.querySelectorAll('[data-language-toggle]');
const languageLabels = document.querySelectorAll('[data-language-label]');
let currentLanguage = 'en';

function setLanguage(language) {
  currentLanguage = language;
  document.documentElement.lang = language === 'ne' ? 'ne' : 'en';
  document.querySelectorAll('[data-i18n]').forEach((node) => {
    const value = translations[language][node.dataset.i18n];
    if (typeof value === 'string') node.textContent = value;
  });
  languageLabels.forEach((node) => { node.textContent = language === 'en' ? 'नेपाली' : 'English'; });
  languageButtons.forEach((button) => button.setAttribute('aria-pressed', String(language === 'ne')));
}

languageButtons.forEach((button) => button.addEventListener('click', () => {
  setLanguage(currentLanguage === 'en' ? 'ne' : 'en');
  closeMenu();
}));

function closeMenu() {
  menuToggle?.classList.remove('is-open');
  menuToggle?.setAttribute('aria-expanded', 'false');
  mobileNav?.classList.remove('is-open');
  mobileNav?.setAttribute('aria-hidden', 'true');
  document.body.classList.remove('is-locked');
}

menuToggle?.addEventListener('click', () => {
  const isOpen = menuToggle.classList.toggle('is-open');
  menuToggle.setAttribute('aria-expanded', String(isOpen));
  mobileNav.classList.toggle('is-open', isOpen);
  mobileNav.setAttribute('aria-hidden', String(!isOpen));
  document.body.classList.toggle('is-locked', isOpen);
});

document.querySelectorAll('.mobile-nav a').forEach((link) => link.addEventListener('click', closeMenu));
const scrollProgress = document.querySelector('[data-scroll-progress]');
let scrollFrame = 0;
const updateViewportState = () => {
  scrollFrame = 0;
  header?.setAttribute('data-scrolled', String(window.scrollY > 24));
  const scrollableHeight = document.documentElement.scrollHeight - window.innerHeight;
  const progress = scrollableHeight > 0 ? Math.min(1, Math.max(0, window.scrollY / scrollableHeight)) : 0;
  scrollProgress?.style.setProperty('--scroll-progress', String(progress));
  document.documentElement.style.setProperty('--scroll-progress', String(progress));
};
const requestViewportState = () => {
  if (!scrollFrame) scrollFrame = window.requestAnimationFrame(updateViewportState);
};
window.addEventListener('scroll', requestViewportState, { passive: true });
window.addEventListener('resize', requestViewportState, { passive: true });
updateViewportState();

const revealNodes = document.querySelectorAll('.reveal');
if ('IntersectionObserver' in window) {
  const revealObserver = new IntersectionObserver((entries) => {
    entries.forEach((entry) => { if (entry.isIntersecting) { entry.target.classList.add('is-visible'); revealObserver.unobserve(entry.target); } });
  }, { threshold: .12 });
  revealNodes.forEach((node) => revealObserver.observe(node));
} else {
  revealNodes.forEach((node) => node.classList.add('is-visible'));
}

const sectionLinks = [...document.querySelectorAll('.desktop-nav a')];
if ('IntersectionObserver' in window) {
  const sectionObserver = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) sectionLinks.forEach((link) => link.classList.toggle('is-active', link.getAttribute('href') === `#${entry.target.id}`));
      if (entry.isIntersecting) sectionLinks.forEach((link) => {
        if (link.getAttribute('href') === `#${entry.target.id}`) link.setAttribute('aria-current', 'location');
        else link.removeAttribute('aria-current');
      });
    });
  }, { rootMargin: '-30% 0px -60% 0px', threshold: 0 });
  document.querySelectorAll('main section[id]').forEach((section) => sectionObserver.observe(section));
}

const lightbox = document.querySelector('[data-lightbox]');
const lightboxImage = document.querySelector('[data-lightbox-image]');
const lightboxCaption = document.querySelector('[data-lightbox-caption]');
const lightboxClose = document.querySelector('[data-lightbox-close]');
const lightboxPrevious = document.querySelector('[data-lightbox-prev]');
const lightboxNext = document.querySelector('[data-lightbox-next]');
const lightboxCount = document.querySelector('[data-lightbox-count]');
const galleryItems = [...document.querySelectorAll('[data-gallery]')];
let activeGalleryIndex = -1;
let lastFocusedGalleryItem = null;

const renderGalleryItem = (item, index) => {
  if (!item || !lightboxImage || !lightboxCaption) return;
  activeGalleryIndex = index;
  lightboxImage.src = item.dataset.image;
  lightboxImage.alt = item.querySelector('img')?.alt || '';
  lightboxCaption.textContent = item.dataset.caption || '';
  if (lightboxCount) lightboxCount.textContent = `${index + 1} / ${galleryItems.length}`;
};

const openLightbox = (item, index) => {
  if (!lightbox) return;
  renderGalleryItem(item, index);
  lightbox.classList.add('is-open');
  lightbox.setAttribute('aria-hidden', 'false');
  document.body.classList.add('is-locked');
  window.setTimeout(() => lightboxClose?.focus({ preventScroll: true }), 0);
};

const closeLightbox = () => {
  if (!lightbox) return;
  lightbox.classList.remove('is-open');
  lightbox.setAttribute('aria-hidden', 'true');
  document.body.classList.remove('is-locked');
  lastFocusedGalleryItem?.focus({ preventScroll: true });
  lastFocusedGalleryItem = null;
  activeGalleryIndex = -1;
};

const moveLightbox = (direction) => {
  if (!galleryItems.length || activeGalleryIndex < 0) return;
  const nextIndex = (activeGalleryIndex + direction + galleryItems.length) % galleryItems.length;
  renderGalleryItem(galleryItems[nextIndex], nextIndex);
};

galleryItems.forEach((item, index) => {
  let touchPressTimer = 0;

  // A short tap still opens the lightbox. A press-and-hold previews the
  // original color treatment until the finger leaves the frame.
  item.addEventListener('pointerdown', (event) => {
    if (event.pointerType !== 'touch') return;
    window.clearTimeout(touchPressTimer);
    touchPressTimer = window.setTimeout(() => item.classList.add('is-colorful'), 160);
  });

  const endTouchPreview = (event) => {
    if (event.pointerType && event.pointerType !== 'touch') return;
    window.clearTimeout(touchPressTimer);
    touchPressTimer = 0;
    item.classList.remove('is-colorful');
  };

  item.addEventListener('pointerup', endTouchPreview);
  item.addEventListener('pointercancel', endTouchPreview);
  item.addEventListener('pointerleave', endTouchPreview);

  item.addEventListener('click', () => {
    lastFocusedGalleryItem = item;
    openLightbox(item, index);
  });
});
lightboxPrevious?.addEventListener('click', () => moveLightbox(-1));
lightboxNext?.addEventListener('click', () => moveLightbox(1));
lightboxClose?.addEventListener('click', closeLightbox);
lightbox?.addEventListener('click', (event) => { if (event.target === lightbox) closeLightbox(); });
document.addEventListener('keydown', (event) => {
  if (lightbox?.classList.contains('is-open')) {
    if (event.key === 'Escape') { closeLightbox(); return; }
    if (event.key === 'ArrowLeft') { event.preventDefault(); moveLightbox(-1); return; }
    if (event.key === 'ArrowRight') { event.preventDefault(); moveLightbox(1); return; }
  }
  if (event.key === 'Escape') closeMenu();
});

document.querySelectorAll('[data-current-year]').forEach((node) => { node.textContent = new Date().getFullYear(); });
